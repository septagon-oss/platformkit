// screenCommand is `platformkit screens`: it writes the reference composition's
// views and anchors to -out and the typed Go references generated from them to
// -refs. It opens nothing, so it runs offline, and `make generate` is its caller.
// A published view or anchor whose binding moved is refused before anything is
// written, so a control cannot be retargeted under a product that names it;
// `make check-generated` then diffs both files against the tree.
func screenCommand(args []string) error {
	flags := flag.NewFlagSet("screens", flag.ContinueOnError)
	configPath := flags.String("config", "config.yaml", "Composition configuration")
	out := flags.String("out", "ui/screens/testdata/screens.json", "Published screen artifact")
	refs := flags.String("refs", "kit/screen/references_generated.go", "Generated Go references")
	base := flags.String("base", "origin/main", "Compatibility merge-base reference")
	if err := flags.Parse(args); err != nil {
		return err
	}
	cfg, err := config.Load(*configPath)
	if err != nil {
		return err
	}
	inventory, err := referenceScreens(cfg)
	if err != nil {
		return err
	}
	if err := screenBaselines(inventory, *out, *base); err != nil {
		return err
	}
	data, err := inventory.Bytes()
	if err != nil {
		return err
	}
	generated, err := screenReferences(inventory)
	if err != nil {
		return err
	}
	for _, written := range []struct {
		path    string
		content []byte
	}{{*out, data}, {*refs, generated}} {
		if err := replaceScreenFile(written.path, written.content); err != nil {
			return err
		}
	}
	return nil
}

// screenReferences names every published view and anchor as a typed constant, so
// a product reaches a screen by identifier rather than by a string it can mistype.
func screenReferences(inventory screen.Inventory) ([]byte, error) {
	snapshot := inventory.Snapshot()
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by go run ./apps/platformkit screens; DO NOT EDIT.\n\npackage screen")
	fmt.Fprintf(&out, "\nconst ReferenceContractHash = %q\n\nconst (\n", snapshot.Hash)
	seen := map[string]bool{}
	write := func(ref, kind string) error {
		name, err := screen.Symbol(ref)
		if err != nil {
			return err
		}
		if seen[name] {
			return fmt.Errorf("screens: identifier collision %s", name)
		}
		seen[name] = true
		fmt.Fprintf(&out, "\t%s %s = %q\n", name, kind, ref)
		return nil
	}
	for _, v := range snapshot.Views {
		if err := write(string(v.ID), "ViewRef"); err != nil {
			return nil, err
		}
		for _, a := range v.Anchors {
			if err := write(string(v.ID)+"#"+a.Name, "AnchorRef"); err != nil {
				return nil, err
			}
		}
	}
	fmt.Fprintln(&out, ")")
	return format.Source(out.Bytes())
}

// replaceScreenFile writes data through a temporary file beside path, so an
// interrupted run leaves the reviewed file complete rather than half written.
func replaceScreenFile(path string, data []byte) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), "."+filepath.Base(path)+".tmp")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}

func referenceScreens(cfg config.Config) (screen.Inventory, error) {
	var first screen.Inventory
	var encoded []byte
	for _, environment := range []pkit.Environment{pkit.Development, pkit.Production} {
		ref := composeReference(cfg, environment)
		inventory, err := ref.app.Screens(context.Background(), ref.once)
		if err != nil {
			return screen.Inventory{}, err
		}
		data, err := inventory.Bytes()
		if err != nil {
			return screen.Inventory{}, err
		}
		if encoded != nil && !bytes.Equal(encoded, data) {
			return screen.Inventory{}, fmt.Errorf("screens: development and production contracts differ")
		}
		first, encoded = inventory, data
	}
	return first, nil
}

func screenBaselines(candidate screen.Inventory, path, base string) error {
	if local, err := os.ReadFile(path); err == nil {
		if err := compatibleScreens(candidate, local); err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	merged, err := exec.Command("git", "merge-base", "HEAD", base).Output()
	if err != nil {
		return fmt.Errorf("screens: unavailable base %s: %w", base, err)
	}
	commit := strings.TrimSpace(string(merged))
	listed, err := exec.Command("git", "ls-tree", "--name-only", commit, "--", filepath.ToSlash(path)).Output()
	if err != nil {
		return fmt.Errorf("screens: read baseline tree: %w", err)
	}
	if len(bytes.TrimSpace(listed)) == 0 {
		return nil
	}
	data, err := exec.Command("git", "show", commit+":"+filepath.ToSlash(path)).Output()
	if err != nil {
		return fmt.Errorf("screens: read baseline artifact: %w", err)
	}
	return compatibleScreens(candidate, data)
}

func compatibleScreens(candidate screen.Inventory, data []byte) error {
	previous, err := screen.ParseSnapshot(data)
	if err != nil {
		return err
	}
	return candidate.Compatible(previous)
}
