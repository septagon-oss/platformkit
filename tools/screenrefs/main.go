// Command screenrefs generates typed Go constants from a reviewed screen artifact.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"

	"github.com/septagon-oss/platformkit/kit/screen"
)

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(args []string) error {
	flags := flag.NewFlagSet("screenrefs", flag.ContinueOnError)
	in := flags.String("in", "ui/screens/testdata/screens.json", "Reviewed artifact")
	out := flags.String("out", "kit/screen/references_generated.go", "Generated Go references")
	check := flags.Bool("check", false, "Refuse missing or stale references without writing")
	if err := flags.Parse(args); err != nil {
		return err
	}
	data, err := os.ReadFile(*in)
	if err != nil {
		return err
	}
	inventory, err := screen.ParseSnapshot(data)
	if err != nil {
		return fmt.Errorf("%s: %w", *in, err)
	}
	generated, err := references(inventory)
	if err != nil {
		return err
	}
	if *check {
		existing, err := os.ReadFile(*out)
		if err != nil {
			return err
		}
		if !bytes.Equal(existing, generated) {
			return fmt.Errorf("%s: generated screen references are stale", *out)
		}
		return nil
	}
	tmp, err := os.CreateTemp("", "screenrefs-*.go")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(generated); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), *out)
}

func references(inventory screen.Inventory) ([]byte, error) {
	data := inventory.Snapshot()
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by go run ./tools/screenrefs; DO NOT EDIT.\n\npackage screen")
	fmt.Fprintf(&out, "\nconst ReferenceContractHash = %q\n\nconst (\n", data.Hash)
	seen := map[string]bool{}
	write := func(ref, kind string) error {
		name, err := screen.Symbol(ref)
		if err != nil {
			return err
		}
		if seen[name] {
			return fmt.Errorf("screenrefs: identifier collision %s", name)
		}
		seen[name] = true
		fmt.Fprintf(&out, "\t%s %s = %q\n", name, kind, ref)
		return nil
	}
	for _, v := range data.Views {
		if err := write(string(v.ID), "ViewRef"); err != nil {
			return nil, err
		}
		for _, a := range v.Anchors {
			if err := write(string(v.ID)+"#"+a.Name, "AnchorRef"); err != nil {
				return nil, err
			}
		}
	}
	fmt.Fprintln(&out, ")")
	return format.Source(out.Bytes())
}
