package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func tree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for name, body := range files {
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func scan(t *testing.T, files map[string]string) Report {
	t.Helper()
	rep, err := Scan(tree(t, files))
	if err != nil {
		t.Fatal(err)
	}
	return rep
}

func TestEachPatternIsRefusedAtItsLine(t *testing.T) {
	for id, text := range map[string]string{
		"review-number":     "// settled in review 3",
		"review-possessive": "// the review's escape route",
		"reviewer-finding":  "// the reviewer's finding was",
		"round":             "// Round 15 raised it",
		"finding":           "// finding 4 showed",
		"task-id":           "// T-0228 carries it",
		"test-file":         "// see a_test.go for it",
	} {
		rep := scan(t, map[string]string{"a.go": "package a\n\n" + text + "\nvar X int\n"})
		if len(rep.Refused) != 1 || rep.Refused[0].Pattern != id || rep.Refused[0].Line != 3 {
			t.Errorf("%s: refused = %+v", id, rep.Refused)
		}
	}
}

func TestBlockCommentLineIsReportedAtItsOwnLine(t *testing.T) {
	rep := scan(t, map[string]string{"a.go": "package a\n\n/*\nfine\nreview 3 said\n*/\nvar X int\n"})
	if len(rep.Refused) != 1 || rep.Refused[0].Line != 5 {
		t.Fatalf("refused = %+v", rep.Refused)
	}
}

func TestPlainWordsAreNotRefused(t *testing.T) {
	rep := scan(t, map[string]string{"a.go": "package a\n\n// review the round; TestX covers it.\n// a test file in prose\nvar X int\n"})
	if len(rep.Refused) != 0 {
		t.Fatalf("refused = %+v", rep.Refused)
	}
}

func TestExemptionsPassWithARefusedString(t *testing.T) {
	cite := "// review 3 and T-0228 and x_test.go\n"
	rep := scan(t, map[string]string{
		"directive.go":  "package a\n\n//go:generate echo T-0228\nvar X int\n",
		"gen.go":        "// Code generated by x. DO NOT EDIT.\n\npackage a\n\n" + cite + "var X int\n",
		"licence.go":    "// Copyright review 3 T-0228\n\npackage a\n",
		"example.go":    "package a\n\n" + cite + "func Example_x() {\n" + cite + "}\n",
		"a_test.go":     "package a\n\n" + cite,
		"testdata/x.go": "package a\n\n" + cite,
	})
	if len(rep.Refused) != 0 {
		t.Fatalf("refused = %+v", rep.Refused)
	}
}

func TestHistoryDirectiveKeepsOneCommentAndPrintsItsReason(t *testing.T) {
	rep := scan(t, map[string]string{"a.go": "package a\n\n//lint:comment-history protocol compat\n// review 3 date\nvar X int\n"})
	if len(rep.Refused) != 0 || len(rep.Exceptions) != 1 || rep.Exceptions[0].Reason != "protocol compat" {
		t.Fatalf("report = %+v", rep)
	}
	if !strings.Contains(rep.Text(), "EXCEPTION a.go:4 protocol compat") {
		t.Fatalf("text = %q", rep.Text())
	}
	rep = scan(t, map[string]string{"a.go": "package a\n\n//lint:comment-history\n// review 3 date\nvar X int\n"})
	if len(rep.Refused) != 1 || rep.Refused[0].Pattern != "exception-reason" {
		t.Fatalf("refused = %+v", rep.Refused)
	}
}

func TestLongBlockStartsAtFifteenLines(t *testing.T) {
	block := func(n int) string { return strings.Repeat("// a line\n", n) }
	rep := scan(t, map[string]string{
		"long.go":  "package a\n\n" + block(15) + "var X int\n",
		"short.go": "package a\n\n" + block(14) + "var X int\n",
	})
	if len(rep.LongBlocks) != 1 || rep.LongBlocks[0].File != "long.go" || rep.LongBlocks[0].Lines != 15 {
		t.Fatalf("long = %+v", rep.LongBlocks)
	}
	if len(rep.Refused) != 0 {
		t.Fatalf("refused = %+v", rep.Refused)
	}
}

func TestPackageCountsAndRatio(t *testing.T) {
	rep := scan(t, map[string]string{
		"p/a.go": "package p\n\n// one\n// two\nvar X int\nvar Y int\n",
		"q/b.go": "package q\n\nvar Z int\n",
	})
	if len(rep.Packages) != 2 || rep.Packages[0].Dir != "p" {
		t.Fatalf("packages = %+v", rep.Packages)
	}
	if p := rep.Packages[0]; p.CommentLines != 2 || p.CodeLines != 3 || p.Ratio < 0.66 || p.Ratio > 0.67 {
		t.Fatalf("p = %+v", p)
	}
	if q := rep.Packages[1]; q.CommentLines != 0 || q.CodeLines != 2 || q.Ratio != 0 {
		t.Fatalf("q = %+v", q)
	}
}

func TestUnparsableFileIsAnError(t *testing.T) {
	if _, err := Scan(tree(t, map[string]string{"a.go": "package"})); err == nil {
		t.Fatal("want an error")
	}
}
