#!/usr/bin/env bash
# Render the aggregate module graph — every module of this repository, its layer,
# and which module reaches which — into docs/MODULE-GRAPH.md. The document is
# generated: the gate measures the tree, so the map cannot rot into a list of
# edges nobody kept up to date. It reads no clock and prints no timestamp, which
# is what lets `make check-generated` ask for the same bytes twice.
#
#   module_graph.sh [repository]        # default: the foundation holding this script
set -euo pipefail
scripts="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "${1:-$(dirname "$scripts")}" && pwd)" || exit 2

measured="$(mktemp)" && rendered="$(mktemp)" && refused="$(mktemp)" || exit 2
trap 'rm -f "$measured" "$rendered" "$refused"' EXIT
# The gate's own diagnostics reach the reader, and only the gate's own: `go run`
# appends a bare `exit status N` line of its own to stderr, which names nothing and
# would sit between the reader and the cause. `--modules` answers a policy refusal
# with the report and status 0, so a nonzero status here is a reading failure — a
# malformed map, a dependency whose tree holds no declaration — whose cause only the
# gate names, and which this script cannot restate.
if ! json="$(cd "$repo" && env GOWORK=off GOFLAGS=-buildvcs=false go run ./tools/importgate --modules . 2>"$refused")"; then
	sed -e '$ { /^exit status [0-9][0-9]*$/d; }' "$refused" >&2
	echo 'module graph: the import gate could not measure this repository' >&2
	exit 2
fi
printf '%s\n' "$json" > "$measured"
python3 - "$measured" <<'PY' > "$rendered"
import json, sys

with open(sys.argv[1], encoding="utf-8") as source:
    graph = json.load(source)
print("# Module graph")
print()
print("Generated by [scripts/module_graph.sh](../scripts/module_graph.sh) from")
print("`go run ./tools/importgate --modules .`: the module graph this repository's own")
print("Go sources measure today. Nothing here is kept by hand, and the direction of")
print("every row is computed from the order below, never declared. Read it beside")
print("[the import gate](../tools/importgate/README.md), which refuses a production")
print("import that climbs the order and refuses a module the order does not place.")
print()
print("## The order")
print()
print("Rank is position. The order belongs to the gate, so a layer name means the same")
print("thing in the kernel, the catalogue and a product repository; each repository")
print("assigns only its own modules, in its own `scripts/imports-layers.txt`.")
print()
print("| Rank | Layer | |")
print("| --- | --- | --- |")
meanings = {
    "platform": "needs no account, no role and no person; works over a tenant id and values",
    "identity": "owns the account, the tenant record, a person's identity, or the channel the platform reaches a person through",
    "generic": "a reusable domain capability composed over the two layers below",
    "product": "the module's reason is an application-facing surface",
}
for rank, layer in enumerate(graph["layers"]):
    print(f"| {rank} | `{layer}` | {meanings[layer]} |")
print()
print("## Modules")
print()
print("| Module | Repository | Layer |")
print("| --- | --- | --- |")
for node in graph["nodes"]:
    print(f"| `{node['module']}` | `{node['repository']}` | `{node['layer']}` |")
print()


def rows(edges, heading, note):
    print(f"## {heading}")
    print()
    print(note)
    print()
    if not edges:
        print("None in this build context.")
        print()
        return
    print("| From | To | Layers | Direction | Contexts | Source | Justified |")
    print("| --- | --- | --- | --- | --- | --- | --- |")
    for edge in edges:
        contexts = sorted({context for package in edge["packages"] for context in package["contexts"]})
        justified = "yes" if edge["justified"] else ""
        print(
            f"| `{edge['from'].rsplit('/', 1)[-1]}` | `{edge['to'].rsplit('/', 1)[-1]}` "
            f"| `{edge['fromLayer']}` -> `{edge['toLayer']}` | {edge['direction']} "
            f"| {', '.join(contexts)} | {', '.join(edge['sources'])} | {justified} |"
        )
    print()


rows(
    graph["edges"],
    "Imports between modules",
    "Package-level imports aggregated by module owner: ordinary source, `contracts/` "
    "and `internal/`. The gate judges the layer rule over `production` contexts alone, "
    "so an `upward` row whose contexts are all test contexts is not a refusal: test "
    "source may read a peer's `contracts/` tree with no row, and "
    "`scripts/imports-integration.txt` is what names the foreign constructors a suite "
    "may compose.",
)
rows(
    graph["constructions"],
    "Composition between modules",
    "Edges whose source is a module's own root package — the composition side, where a "
    "provider names a peer's contracts to wire what it Provides. Printed apart from the "
    "rows above because Go package imports cannot cycle while module composition can: a "
    "pair that appears here in both directions is one unit of composition, and its reason "
    "is the justification row in `scripts/imports-layers.txt`.",
)
PY
mkdir -p "$repo/docs"
mv "$rendered" "$repo/docs/MODULE-GRAPH.md"
echo "module graph: docs/MODULE-GRAPH.md holds $(wc -l < "$repo/docs/MODULE-GRAPH.md") lines of the measured graph"
